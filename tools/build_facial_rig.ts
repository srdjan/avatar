import { build, stop } from "npm:esbuild@0.25.9";

const root = new URL("../", import.meta.url);
const entryPoint = new URL("browser/facial_rig.ts", root);
const outputPath = new URL("assets/private/facial-rig.js", root);
const checkOnly = Deno.args.includes("--check");

try {
  const result = await build({
    absWorkingDir: root.pathname,
    banner: { js: "// Generated by `deno task browser:build`. Do not edit." },
    bundle: true,
    charset: "utf8",
    entryPoints: [entryPoint.pathname],
    format: "iife",
    legalComments: "none",
    logLevel: "silent",
    minify: false,
    platform: "browser",
    target: "es2022",
    treeShaking: true,
    write: false,
  });
  const output = result.outputFiles?.[0];
  if (output === undefined) throw new Error("browser build produced no output");
  const generated = await formatJavaScript(new TextDecoder().decode(output.contents));
  if (checkOnly) {
    const current = await Deno.readTextFile(outputPath);
    if (current !== generated) {
      throw new Error("facial-rig.js is stale; run `deno task browser:build`");
    }
  } else {
    await Deno.writeTextFile(outputPath, generated);
  }
} finally {
  stop();
}

async function formatJavaScript(source: string): Promise<string> {
  const process = new Deno.Command(Deno.execPath(), {
    args: ["fmt", "--ext=js", "-"],
    stdin: "piped",
    stdout: "piped",
    stderr: "piped",
  }).spawn();
  const writer = process.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();
  const output = await process.output();
  if (!output.success) throw new Error(new TextDecoder().decode(output.stderr));
  return new TextDecoder().decode(output.stdout);
}
